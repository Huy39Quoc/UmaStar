package umastar.enums;

/** Thời điểm ghi nhận nhật ký tình trạng sức khỏe ngựa trên chuyến đi. */
public enum HorseConditionStage {
    /** Kiểm tra và chụp ảnh khi đón ngựa lên phương tiện trước giờ khởi hành. */
    PRE_DEPARTURE,
    /** Theo dõi định kỳ trong suốt quá trình vận chuyển. */
    IN_TRANSIT,
    /** Kiểm tra tình trạng ngựa khi tới điểm đến chuẩn bị bàn giao. */
    ON_ARRIVAL
}

